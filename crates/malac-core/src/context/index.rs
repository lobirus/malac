/// Names a C-like function pattern must not take for a symbol.
const C_KEYWORDS: &[&str] = &[
    "if", "for", "while", "switch", "return", "sizeof", "else", "do", "case",
];

fn symbols(extractor: Extractor, text: &str) -> Vec<String> {
    let patterns: &[Pattern] = match extractor {
        Extractor::Rust => &RUST,
        Extractor::Script => &SCRIPT,
        Extractor::Python => &PYTHON,
        Extractor::Go => &GO,
        Extractor::Jvm => &JVM,
        Extractor::C => &C,
        Extractor::Ruby => &RUBY,
        Extractor::Shell => &SHELL,
        Extractor::Elixir => &ELIXIR,
        Extractor::Lua => &LUA,
        Extractor::Markdown | Extractor::None => return Vec::new(),
    };
    let mut out: Vec<String> = Vec::new();
    let mut seen = BTreeSet::new();
    for line in text.lines() {
        if line.is_empty()
            || line.starts_with(['/', '#', '*', '}', ')', ' ', '\t'])
                && !matches!(extractor, Extractor::Ruby | Extractor::Elixir)
        {
            continue;
        }
        let Some((pattern, caps)) = patterns
            .iter()
            .find_map(|p| p.regex.captures(line).map(|c| (p, c)))
        else {
            continue;
        };
        let group = |name: &str| caps.name(name).map_or("", |m| m.as_str());
        if extractor == Extractor::C && C_KEYWORDS.contains(&group("name")) {
            continue;
        }
        let symbol = pattern
            .format
            .replace("{vis}", group("vis"))
            .replace(
                "{kind}",
                &group("kind")
                    .split_whitespace()
                    .collect::<Vec<_>>()
                    .join(" "),
            )
            .replace("{name}", group("name").trim())
            .replace("{recv}", group("recv").trim());
        let symbol = symbol.split_whitespace().collect::<Vec<_>>().join(" ");
        if seen.insert(symbol.clone()) {
            out.push(symbol);
        }
        if out.len() >= MAX_SYMBOLS_PER_FILE {
            break;
        }
    }
    out
}

fn headings(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_code = false;
    for line in text.lines() {
        if line.starts_with("```") || line.starts_with("~~~") {
            in_code = !in_code;
            continue;
        }
        if in_code {
            continue;
        }
        let level = line.chars().take_while(|c| *c == '#').count();
        if (1..=3).contains(&level) && line[level..].starts_with(' ') {
            out.push(line[level..].trim().to_owned());
            if out.len() >= MAX_HEADINGS_PER_FILE {
                break;
            }
        }
    }
    out
}

