fn file_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn depth(path: &str) -> usize {
    path.matches('/').count()
}

fn is_manifest(path: &str) -> bool {
    let name = file_name(path);
    MANIFESTS.contains(&name) || name.ends_with(".csproj") || name.ends_with(".sln")
}

fn is_entry_point(path: &str) -> bool {
    let name = file_name(path);
    let parent = path.rsplit_once('/').map_or("", |(p, _)| p);
    let parent_name = file_name(parent);
    match name {
        "main.rs" | "lib.rs" => parent_name == "src",
        "main.go" => true,
        "__main__.py" | "manage.py" | "wsgi.py" | "asgi.py" => true,
        "main.py" | "app.py" | "cli.py" => depth(path) <= 2,
        "Program.cs" | "Main.java" | "Main.kt" | "main.swift" => true,
        _ => {
            let stem = name.split('.').next().unwrap_or(name);
            let ext = name.rsplit('.').next().unwrap_or("");
            let script = matches!(ext, "ts" | "tsx" | "js" | "jsx" | "mjs");
            (script
                && matches!(stem, "index" | "main" | "server" | "app" | "App")
                && (parent.is_empty() || parent_name == "src")
                && depth(path) <= 3)
                || (parent_name == "bin" && path.contains("src/bin/") && ext == "rs")
        }
    }
}

/// One line describing a manifest: the package name, workspace members,
/// scripts or binaries it declares.
fn describe_manifest(root: &Path, path: &str) -> String {
    let full = root.join(path);
    let read = || std::fs::read_to_string(&full).ok();
    let mut parts: Vec<String> = Vec::new();
    match file_name(path) {
        "Cargo.toml" => {
            if let Some(table) = read().and_then(|t| t.parse::<toml::Table>().ok()) {
                if let Some(name) = table
                    .get("package")
                    .and_then(|p| p.get("name"))
                    .and_then(|n| n.as_str())
                {
                    parts.push(format!("crate {name}"));
                }
                if let Some(members) = table
                    .get("workspace")
                    .and_then(|w| w.get("members"))
                    .and_then(|m| m.as_array())
                {
                    let members: Vec<&str> = members.iter().filter_map(|m| m.as_str()).collect();
                    parts.push(format!("workspace: {}", members.join(", ")));
                }
                if let Some(bins) = table.get("bin").and_then(|b| b.as_array()) {
                    let names: Vec<&str> = bins
                        .iter()
                        .filter_map(|b| b.get("name")?.as_str())
                        .collect();
                    if !names.is_empty() {
                        parts.push(format!("bins: {}", names.join(", ")));
                    }
                }
            }
        }
        "package.json" => {
            if let Some(json) =
                read().and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
            {
                if let Some(name) = json["name"].as_str() {
                    parts.push(name.to_owned());
                }
                if let Some(main) = json["main"].as_str() {
                    parts.push(format!("main {main}"));
                }
                match &json["bin"] {
                    serde_json::Value::String(bin) => parts.push(format!("bin {bin}")),
                    serde_json::Value::Object(bins) => parts.push(format!(
                        "bin {}",
                        bins.keys().cloned().collect::<Vec<_>>().join(", ")
                    )),
                    _ => {}
                }
                if let Some(scripts) = json["scripts"].as_object() {
                    let names: Vec<&str> = scripts.keys().map(String::as_str).take(12).collect();
                    parts.push(format!("scripts: {}", names.join(", ")));
                }
                if let Some(workspaces) = json["workspaces"].as_array() {
                    let names: Vec<&str> = workspaces.iter().filter_map(|w| w.as_str()).collect();
                    parts.push(format!("workspaces: {}", names.join(", ")));
                }
            }
        }
        "pyproject.toml" => {
            if let Some(table) = read().and_then(|t| t.parse::<toml::Table>().ok()) {
                let project = table.get("project");
                if let Some(name) = project.and_then(|p| p.get("name")).and_then(|n| n.as_str()) {
                    parts.push(name.to_owned());
                }
                if let Some(scripts) = project
                    .and_then(|p| p.get("scripts"))
                    .and_then(|s| s.as_table())
                {
                    parts.push(format!(
                        "scripts: {}",
                        scripts.keys().cloned().collect::<Vec<_>>().join(", ")
                    ));
                }
            }
        }
        "go.mod" => {
            if let Some(module) = read().and_then(|t| {
                t.lines()
                    .find_map(|l| l.strip_prefix("module ").map(|m| m.trim().to_owned()))
            }) {
                parts.push(format!("module {module}"));
            }
        }
        _ => {}
    }
    if parts.is_empty() {
        format!("- {path}")
    } else {
        format!("- {path} ({})", parts.join("; "))
    }
}

fn render(root: &Path, files: &BTreeMap<String, FileEntry>, notes: &str) -> String {
    let mut out = String::from("# Project index\n\n");
    out.push_str(
        "<!-- Generated by malac from this repository's files (`malac index` rebuilds it). \
         Only the Notes section is kept when it is regenerated; add to it with the project_index tool. -->\n\n",
    );
    out.push_str(&format!(
        "Updated {} · {} files · Sections: Overview, Tree, Docs, Symbols, Notes\n\n",
        Utc::now().format("%Y-%m-%d %H:%M UTC"),
        files.len()
    ));

    // Overview.
    out.push_str("## Overview\n\n");
    let mut languages: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    for (path, entry) in files {
        if let Some(lang) = language(Path::new(path)) {
            let slot = languages.entry(lang.name).or_default();
            slot.0 += 1;
            slot.1 += entry.lines;
        }
    }
    let mut ranked: Vec<(&str, (usize, usize))> = languages.into_iter().collect();
    ranked.sort_by(|a, b| b.1.1.cmp(&a.1.1).then(b.1.0.cmp(&a.1.0)));
    if !ranked.is_empty() {
        let list: Vec<String> = ranked
            .iter()
            .take(12)
            .map(|(name, (count, lines))| format!("{name} {count} ({lines} lines)"))
            .collect();
        out.push_str(&format!("Languages: {}\n\n", list.join(", ")));
    }
    let manifests: Vec<String> = files
        .keys()
        .filter(|p| is_manifest(p) && depth(p) <= 3)
        .take(40)
        .map(|p| describe_manifest(root, p))
        .collect();
    if !manifests.is_empty() {
        out.push_str(&format!("Manifests:\n{}\n\n", manifests.join("\n")));
    }
    let entries: Vec<&String> = files
        .keys()
        .filter(|p| is_entry_point(p))
        .take(30)
        .collect();
    if !entries.is_empty() {
        let list: Vec<String> = entries.iter().map(|p| format!("- {p}")).collect();
        out.push_str(&format!("Entry points:\n{}\n\n", list.join("\n")));
    }

    // Tree.
    out.push_str("## Tree\n\n");
    out.push_str(&tree(files.keys().map(String::as_str)));
    out.push('\n');

    // Docs.
    out.push_str("## Docs\n\n");
    let docs: Vec<String> = files
        .iter()
        .filter(|(_, e)| !e.headings.is_empty())
        .map(|(path, e)| format!("- {path}: {}", e.headings.join(" › ")))
        .collect();
    if docs.is_empty() {
        out.push_str("(none)\n");
    } else {
        out.push_str(&docs.join("\n"));
        out.push('\n');
    }
    out.push('\n');

    // Symbols, grouped by directory.
    out.push_str("## Symbols\n\n");
    let mut by_dir: BTreeMap<&str, Vec<(&str, &FileEntry)>> = BTreeMap::new();
    for (path, entry) in files.iter().filter(|(_, e)| !e.symbols.is_empty()) {
        let (dir, name) = path.rsplit_once('/').unwrap_or(("", path.as_str()));
        by_dir.entry(dir).or_default().push((name, entry));
    }
    if by_dir.is_empty() {
        out.push_str("(none)\n\n");
    }
    for (dir, entries) in by_dir {
        out.push_str(&format!(
            "### {}\n\n",
            if dir.is_empty() { "." } else { dir }
        ));
        for (name, entry) in entries {
            out.push_str(&format!("- {name}: {}\n", entry.symbols.join(", ")));
        }
        out.push('\n');
    }

    out.push_str(NOTES);
    out.push_str("\n\n");
    out.push_str(notes.trim());
    out.push('\n');
    out
}

/// Directories with recursive file counts, as deep as fits in
/// `MAX_TREE_LINES`, then the files at the root.
fn tree<'a>(paths: impl Iterator<Item = &'a str>) -> String {
    let mut counts: BTreeMap<String, usize> = BTreeMap::new();
    let mut root_files = Vec::new();
    for path in paths {
        let parts: Vec<&str> = path.split('/').collect();
        if parts.len() == 1 {
            root_files.push(path);
        }
        for end in 1..parts.len() {
            *counts.entry(parts[..end].join("/")).or_default() += 1;
        }
    }
    let mut max_depth = 4;
    while max_depth > 1 && counts.keys().filter(|d| depth(d) < max_depth).count() > MAX_TREE_LINES {
        max_depth -= 1;
    }
    let mut lines: Vec<String> = counts
        .iter()
        .filter(|(dir, _)| depth(dir) < max_depth)
        .take(MAX_TREE_LINES)
        .map(|(dir, count)| {
            let indent = "  ".repeat(depth(dir));
            format!("{indent}- {}/ ({count})", file_name(dir))
        })
        .collect();
    lines.extend(root_files.iter().take(60).map(|f| format!("- {f}")));
    if lines.is_empty() {
        "(empty)\n".into()
    } else {
        lines.join("\n") + "\n"
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(root: &Path, path: &str, text: &str) {
        let path = root.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    #[test]
    fn finds_symbols_per_language() {
        let rust = "pub struct Runtime {\n    x: u32,\n}\nimpl Runtime {\n    pub fn new() {}\n}\nimpl<T: Clone> Tool for Wrapper<T> {\n}\npub(crate) async fn spawn() {}\nconst MAX: usize = 3;\nmacro_rules! log {\n}\n";
        assert_eq!(
            symbols(Extractor::Rust, rust),
            vec![
                "pub struct Runtime",
                "impl Runtime",
                "impl Tool for Wrapper<T>",
                "pub(crate) fn spawn",
                "const MAX",
                "macro log!"
            ]
        );
        let ts = "export default class App {}\nexport interface Props { a: string }\nexport const routes = [];\nfunction helper() {}\nconst local = 1;\n";
        assert_eq!(
            symbols(Extractor::Script, ts),
            vec![
                "export default class App",
                "export interface Props",
                "export const routes",
                "function helper"
            ]
        );
        let py = "import os\n\nclass Store:\n    def get(self):\n        pass\n\nasync def main():\n    pass\n";
        assert_eq!(
            symbols(Extractor::Python, py),
            vec!["class Store", "async def main"]
        );
        let go = "package main\n\ntype Server struct {\n}\n\nfunc (s *Server) Start() error {\n}\n\nfunc main() {\n}\n";
        assert_eq!(
            symbols(Extractor::Go, go),
            vec!["type Server struct", "func (s *Server) Start", "func main"]
        );
        let java = "package x;\n\npublic final class Parser {\n    public void parse() {}\n}\n";
        assert_eq!(symbols(Extractor::Jvm, java), vec!["class Parser"]);
        let c = "#include <stdio.h>\n\nstruct point {\n};\n\nstatic int add(int a, int b)\n{\n    if (a) {}\n}\n";
        assert_eq!(symbols(Extractor::C, c), vec!["struct point", "add()"]);
        let sh = "#!/bin/sh\nusage() {\n  echo\n}\nfunction build {\n}\n";
        assert_eq!(symbols(Extractor::Shell, sh), vec!["usage()", "build()"]);
    }

    #[test]
    fn builds_incrementally_and_keeps_notes() {
        let project = tempfile::tempdir().unwrap();
        let root = project.path();
        write(root, ".gitignore", "target/\n");
        write(root, "Cargo.toml", "[package]\nname = \"demo\"\n");
        write(root, "src/main.rs", "fn main() {}\n");
        write(root, "src/lib.rs", "pub mod parser;\npub fn run() {}\n");
        write(
            root,
            "web/package.json",
            "{\"name\": \"web\", \"scripts\": {\"dev\": \"vite\", \"build\": \"vite build\"}}",
        );
        write(root, "web/src/index.ts", "export function start() {}\n");
        write(
            root,
            "docs/guide.md",
            "# Guide\n\n## Install\n\n```\n# not a heading\n```\n",
        );
        write(root, "target/debug/junk.rs", "fn ignored() {}\n");

        let index = Index::new(root, 100);
        let first = index.refresh(false).unwrap();
        assert!(first.written);
        assert_eq!(first.files, 6);
        let text = index.read().unwrap();
        assert!(text.contains("Rust 2"));
        assert!(text.contains("- Cargo.toml (crate demo)"));
        assert!(text.contains("- web/package.json (web; scripts: "));
        assert!(text.contains("- src/main.rs"));
        assert!(text.contains("- src/ (2)"));
        assert!(text.contains("- docs/guide.md: Guide › Install"));
        assert!(
            text.contains("### src\n\n- lib.rs: pub mod parser, pub fn run\n- main.rs: fn main")
        );
        assert!(!text.contains("ignored"));
        let gitignore = std::fs::read_to_string(root.join(".malac/.gitignore")).unwrap();
        assert!(gitignore.contains("index.md") && gitignore.contains("index.cache.json"));

        index.add_note("Parsing lives in src/parser.rs").unwrap();
        let unchanged = index.refresh(false).unwrap();
        assert_eq!(unchanged.parsed, 0);
        assert!(!unchanged.written);

        write(root, "src/parser.rs", "pub fn parse() {}\n");
        let second = index.refresh(false).unwrap();
        assert_eq!(second.parsed, 1);
        let text = index.read().unwrap();
        assert!(text.contains("- parser.rs: pub fn parse"));
        assert!(text.contains("Parsing lives in src/parser.rs"));
        assert!(!text.contains(NO_NOTES));

        let symbols = index.section("symbols", Some("web")).unwrap();
        assert!(symbols.contains("### web/src\n- index.ts: export function start"));
        assert!(!symbols.contains("main.rs"));
        let hits = index.search("parse", 10).unwrap();
        assert!(
            hits.iter()
                .any(|h| h == "[symbols] src/parser.rs: pub fn parse")
        );
        assert!(hits.iter().any(|h| h.starts_with("[notes]")));
        assert_eq!(index.status().files, 7);
    }
}
