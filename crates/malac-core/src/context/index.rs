fn language(path: &Path) -> Option<Language> {
    let ext = path.extension()?.to_str()?.to_ascii_lowercase();
    LANGUAGES
        .iter()
        .find(|(exts, _, _)| exts.contains(&ext.as_str()))
        .map(|(_, name, extractor)| Language {
            name,
            extractor: *extractor,
        })
}

struct Pattern {
    regex: Regex,
    /// `{vis}`, `{kind}`, `{name}` and `{recv}` are replaced by the groups.
    format: &'static str,
}

fn patterns(spec: &[(&str, &'static str)]) -> Vec<Pattern> {
    spec.iter()
        .map(|(regex, format)| Pattern {
            regex: Regex::new(regex).expect("symbol pattern compiles"),
            format,
        })
        .collect()
}

